#!/usr/bin/env node
/**
 * Reads index/pictures/posters/palettes.json and injects per-event CSS vars
 * + a `poster-treatment` class on each event detail page.
 *
 * For each events/*.html (except event-template.html):
 *   1. Find the hero poster filename from <section class="event-container">
 *      <div class="event-image"><img src="...posters/<file>"
 *   2. Look up palette in palettes.json.
 *   3. Insert / update an inline <style id="poster-palette"> block in <head>
 *      with --poster-primary, --poster-secondary, --poster-fg-on-primary,
 *      --poster-fg-on-secondary on :root.
 *   4. Ensure the <body> tag has class="poster-treatment".
 *
 * Idempotent — running it twice produces the same output.
 *
 * Run locally:  node scripts/inject-poster-palettes.mjs
 */

import { readFile, writeFile, readdir } from "node:fs/promises";
import { resolve, dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PALETTE_FILE = resolve(ROOT, "index/pictures/posters/palettes.json");
const EVENTS_DIR = resolve(ROOT, "events");

const POSTER_FROM_HERO = /<section class="(?:event-container|event-hero)">[\s\S]*?<img\s[^>]*?src="[^"]*posters\/([^"\/]+)"/i;
const STYLE_BLOCK_RE = /<style id="poster-palette">[\s\S]*?<\/style>\s*/i;
const FONT_LINK_RE  = /<link[^>]*\sid="poster-font"[^>]*>\s*/i;
const BODY_OPEN_RE  = /<body(\s[^>]*)?>/i;
const HEAD_CLOSE_RE = /<\/head>/i;

function fontLinkFor(family) {
  if (!family) return "";
  // Google Fonts URL: family name with spaces replaced by '+'.
  const slug = family.replace(/ /g, "+");
  return (
    `<link rel="stylesheet" id="poster-font" ` +
    `href="https://fonts.googleapis.com/css2?family=${slug}:wght@400;700&display=swap">`
  );
}

function styleBlockFor(palette, posterFile) {
  return [
    `<style id="poster-palette">`,
    `    /* Per-event palette sampled from ${posterFile}. Auto-generated;`,
    `       regenerated by scripts/inject-poster-palettes.mjs. */`,
    `    :root {`,
    `      --poster-primary:   ${palette.primary};`,
    `      --poster-secondary: ${palette.secondary};`,
    `      --poster-text:      ${palette.text || palette.secondary};`,
    `      --poster-font-display: ${palette.fontCss || "'Cormorant Garamond', Georgia, serif"};`,
    `      --poster-fg-on-primary:   ${palette.textOnPrimary};`,
    `      --poster-fg-on-secondary: ${palette.textOnSecondary};`,
    `    }`,
    `  </style>`,
  ].join("\n  ");
}

function ensureBodyHasClass(html, cls) {
  return html.replace(BODY_OPEN_RE, (m, attrs) => {
    attrs = attrs || "";
    const classMatch = attrs.match(/class="([^"]*)"/);
    if (classMatch) {
      const classes = classMatch[1].split(/\s+/).filter(Boolean);
      if (classes.includes(cls)) return m;
      const next = (classMatch[1] + " " + cls).trim();
      return `<body${attrs.replace(/class="[^"]*"/, `class="${next}"`)}>`;
    }
    return `<body${attrs} class="${cls}">`;
  });
}

async function patchFile(file, palettes) {
  let html = await readFile(file, "utf8");
  const m = html.match(POSTER_FROM_HERO);
  if (!m) {
    return { file: basename(file), status: "no hero poster found" };
  }
  const poster = m[1];
  const palette = palettes[poster];
  if (!palette) {
    return { file: basename(file), status: `no palette for ${poster}` };
  }

  const styleBlock = styleBlockFor(palette, poster);
  const fontLink   = fontLinkFor(palette.font);

  // Strip any previous palette + font link (idempotent).
  if (STYLE_BLOCK_RE.test(html)) html = html.replace(STYLE_BLOCK_RE, "");
  if (FONT_LINK_RE.test(html))   html = html.replace(FONT_LINK_RE, "");

  // Inject font link + style block just before </head>.
  html = html.replace(
    HEAD_CLOSE_RE,
    `${fontLink ? fontLink + "\n  " : ""}${styleBlock}\n</head>`
  );
  // Add .poster-treatment to <body>.
  html = ensureBodyHasClass(html, "poster-treatment");

  await writeFile(file, html);
  return { file: basename(file), status: "ok", poster, ...palette };
}

async function main() {
  const palettes = JSON.parse(await readFile(PALETTE_FILE, "utf8"));
  const files = (await readdir(EVENTS_DIR))
    .filter((f) => f.endsWith(".html") && f !== "event-template.html")
    .sort();

  const results = [];
  for (const f of files) {
    results.push(await patchFile(join(EVENTS_DIR, f), palettes));
  }

  const ok = results.filter((r) => r.status === "ok");
  const fail = results.filter((r) => r.status !== "ok");

  for (const r of ok) {
    console.log(
      `  ${r.file.padEnd(45)} → ${r.poster.padEnd(40)} ${r.primary}`
    );
  }
  for (const r of fail) {
    console.warn(`  ${r.file}: ${r.status}`);
  }
  console.log(`\nPatched ${ok.length}/${results.length} event pages`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
